"""
Профіль "оператора" — персональний почерк роботи мишею на час сесії.

Навіщо: навіть ідеально людяний окремий рух видає бота, якщо всі рухи
статистично однакові. У живої людини є стала манера — своя швидкість, своя
схильність промахуватись у певний бік, своя частота опитування миші (це
взагалі властивість заліза й не змінюється в межах сесії), — і водночас
повільний дрейф: за півгодини роботи людина втомлюється, рухи стають
повільнішими, промахів і корекцій більшає.

Тому параметри діляться на три групи:
  * **сталі для сесії** — частота опитування, закон Фітца, систематичний зсув
    прицілу, знак викривлення траєкторії (у правші рухи вигинаються стабільно
    в один бік);
  * **похідні від втоми** — множники швидкості, тремору, схильності до
    корекцій; змінюються повільно й монотонно;
  * **разові** — розігруються на кожен рух окремо.
"""
import random
import time
from dataclasses import dataclass, field
from typing import Tuple

__all__ = ["OperatorProfile", "get_profile", "set_profile", "new_profile"]

# Частота опитування миші — характеристика заліза, а не людини: у межах
# сесії вона не змінюється. Ваги приблизно відповідають поширеності: офісні
# миші здебільшого 125 Гц, ігрові — 500/1000 Гц.
_POLLING_RATES: Tuple[Tuple[int, float], ...] = (
    (125, 0.55),
    (250, 0.15),
    (500, 0.18),
    (1000, 0.12),
)


@dataclass
class OperatorProfile:
    """Набір параметрів, що визначає манеру роботи мишею.

    Створюється один раз на сесію (`new_profile()`), далі повільно "втомлюється".
    """

    # --- залізо ---
    polling_hz: int = 125
    # Відхилення періоду опитування у ЧАСТКАХ від номіналу: кварц у миші не
    # ідеальний, але й не "гуляє" на десятки відсотків. Реально це одиниці
    # відсотків, тому величина відносна — на 1000 Гц абсолютний джитер має
    # бути у вісім разів меншим, ніж на 125 Гц.
    polling_jitter: float = 0.02

    # --- закон Фітца: T = a + b * log2(2D / W) ---
    # Тривалість наведення залежить не лише від відстані, а й від розміру цілі:
    # у дрібну кнопку людина цілиться помітно довше. Бот, у якого час руху
    # залежить тільки від відстані, на дрібних цілях вирізняється одразу.
    fitts_a: float = 0.08
    fitts_b: float = 0.10

    # --- прицілювання ---
    # Систематичний зсув: кожна людина стабільно б'є трохи повз центр.
    aim_bias: Tuple[float, float] = (0.0, 0.0)
    # Частка від дистанції, що йде в розкид кінцевої точки первинного руху.
    endpoint_noise: float = 0.055
    # Схильність до перельоту цілі (0..1).
    overshoot_tendency: float = 0.35
    # Ймовірність натиснути кнопку ще до повної зупинки — «на льоту»,
    # під час останнього довідного руху. Нуль означав би, що курсор перед
    # кожним кліком обов'язково завмирає, а це поведінка механізму, не руки.
    press_on_arrival_chance: float = 0.30
    # Частка кліків, де під час утримання кнопки курсор стоїть абсолютно
    # нерухомо. Заміряно на живій руці: таких близько 2/3. Решта йде через
    # idle-тремор. Без цього бот рухається у 100% утримань — головний тел кліку.
    press_still_chance: float = 0.65
    # Знак і сила викривлення траєкторії. Знак сталий: рука людини вигинає
    # рух в один і той самий бік, а не випадково в різні.
    curvature_bias: float = 0.02

    # --- тремор ---
    tremor_amp: float = 0.35        # px, фізіологічний тремор 8-12 Гц
    tremor_hz: float = 9.5
    drift_amp: float = 0.9          # px, повільне "гуляння" руки 1-3 Гц
    drift_hz: float = 1.8

    # Ймовірність, що в довгій паузі руку знято з миші й курсор справді
    # завмер. Нуль був би так само неправдоподібний, як і одиниця: людина
    # то тримає руку на миші, то ні.
    hand_off_chance: float = 0.25
    # Поточний стан «рука на миші» і середнє перебування в стані (секунд
    # простою). Стан живе між паузами — див. `_rest`.
    hand_resting: bool = True
    hand_state_dwell: float = 20.0

    # Ймовірність, що пауза після дії отримає довгий хвіст (секунди).
    long_pause_chance: float = 0.05

    # Стеля швидкості курсора, px/с. Рука фізично не може розігнати мишу
    # швидше, і жодна подія не має нести більший зсув, ніж стеля за такт.
    # Без цієї межі поодинокі промахи регулятора вилітали стрибками на
    # сотні пікселів за одну подію — чого в людини не буває взагалі.
    max_velocity: float = 6000.0

    # --- час ---
    speed_scale: float = 1.0        # <1 — швидше за середнє
    reaction_median: float = 0.19   # пауза "побачив -> почав рухатись"
    # Відкалібровано по запису живої руки: медіана 97 мс, sigma 0.25.
    #
    # Історія цього числа варта уваги. Спершу sigma оцінювалась через
    # коефіцієнт варіації і вийшла 0.75. Формула алгебраїчно правильна,
    # але це метод моментів — він тримається на правому хвості. У записі
    # було 76 натискань, і чотири з них тривали 376-830 мс: це не кліки,
    # а перетягування. Ці чотири події втричі роздули оцінку, і бот почав
    # клацати по пів секунди частіше за людину. Тепер розкид рахується по
    # логарифмах і лише по натисканнях, коротших за третину секунди.
    click_hold_median: float = 0.097
    click_hold_sigma: float = 0.25

    # --- втома ---
    started_at: float = field(default_factory=time.perf_counter)
    actions_done: int = 0

    # ------------------------------------------------------------------
    # Похідні величини з урахуванням втоми
    # ------------------------------------------------------------------

    @property
    def fatigue(self) -> float:
        """Рівень втоми 0..1 — росте від часу роботи й кількості дій.

        Насичується: після ~40 хвилин / ~1500 дій далі майже не змінюється,
        бо нескінченне сповільнення виглядало б так само неправдоподібно,
        як його повна відсутність.
        """
        by_time = (time.perf_counter() - self.started_at) / 2400.0
        by_actions = self.actions_done / 1500.0
        return min(1.0, by_time + by_actions)

    @property
    def current_speed_scale(self) -> float:
        """Множник тривалості рухів: втомлена рука повільніша до ~20%."""
        return self.speed_scale * (1.0 + 0.20 * self.fatigue)

    @property
    def current_tremor_amp(self) -> float:
        """Втомлена рука тремтить помітніше."""
        return self.tremor_amp * (1.0 + 0.6 * self.fatigue)

    @property
    def current_endpoint_noise(self) -> float:
        """Втомлена рука точніше не стає."""
        return self.endpoint_noise * (1.0 + 0.35 * self.fatigue)

    @property
    def polling_interval(self) -> float:
        """Номінальний період між подіями руху, секунди."""
        return 1.0 / self.polling_hz

    def note_action(self) -> None:
        """Відмічає виконану дію — накопичує втому."""
        self.actions_done += 1


def new_profile(seed: int = None) -> OperatorProfile:
    """Створює випадковий профіль оператора.

    Args:
        seed: Якщо заданий — профіль відтворюваний. Потрібно для тестів і
              для порівняння прогонів у `tools/mouse_stats.py`; у бою лишай
              None, інакше "унікальність" почерку стане константою.
    """
    rng = random.Random(seed)

    rates, weights = zip(*_POLLING_RATES)
    polling_hz = rng.choices(rates, weights=weights, k=1)[0]

    # Знак викривлення сталий на сесію — це "рука", а не шум.
    curvature_sign = rng.choice((-1.0, 1.0))

    return OperatorProfile(
        polling_hz=polling_hz,
        polling_jitter=rng.uniform(0.012, 0.045),
        fitts_a=rng.uniform(0.05, 0.12),
        fitts_b=rng.uniform(0.075, 0.135),
        aim_bias=(rng.gauss(0.0, 0.8), rng.gauss(0.0, 0.8)),
        endpoint_noise=rng.uniform(0.04, 0.075),
        overshoot_tendency=rng.uniform(0.18, 0.45),
        press_on_arrival_chance=rng.uniform(0.20, 0.45),
        press_still_chance=rng.uniform(0.55, 0.75),
        curvature_bias=curvature_sign * rng.uniform(0.008, 0.035),
        tremor_amp=rng.uniform(0.20, 0.55),
        tremor_hz=rng.uniform(8.0, 11.5),
        drift_amp=rng.uniform(0.5, 1.4),
        drift_hz=rng.uniform(1.1, 2.6),
        hand_off_chance=rng.uniform(0.10, 0.40),
        hand_state_dwell=rng.uniform(12.0, 35.0),
        long_pause_chance=rng.uniform(0.03, 0.08),
        max_velocity=rng.uniform(5000.0, 9000.0),
        speed_scale=rng.uniform(0.82, 1.25),
        reaction_median=rng.uniform(0.14, 0.26),
        click_hold_median=rng.uniform(0.070, 0.120),
        click_hold_sigma=rng.uniform(0.20, 0.38),
    )


_profile: OperatorProfile = None


def get_profile() -> OperatorProfile:
    """Повертає профіль поточної сесії, створюючи його за першим зверненням."""
    global _profile
    if _profile is None:
        _profile = new_profile()
    return _profile


def set_profile(profile: OperatorProfile) -> None:
    """Встановлює профіль сесії (наприклад, відтворюваний, з `new_profile(seed)`)."""
    global _profile
    _profile = profile
